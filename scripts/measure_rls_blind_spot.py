"""How often can a static RLS scan see anything at all? Measured on n≈190.

WHY THIS EXISTS. SUPABASE_RLS_YIELD_PLAN.md's Part A found that 3 of 7
Supabase-using repos commit no schema — "undetermined, not secure", the
population the live probe exists for. Three out of seven is not a rate. Its
95% interval runs from 16% to 84%, which spans "static analysis covers most of
this market" and "static analysis covers almost none of it", and those two
worlds want different products. This script replaces that 7 with a number big
enough to distinguish them.

IT MEASURES ONE THING: given a vibe-coded repository that uses Supabase, does
it commit its schema? That is the coverage question. Everything else here —
which tables look private, which are anon-readable — is computed with the
SHIPPED detector (app.scan.rls) and reported as a secondary read, because the
detector is already written and running it over 190 repos costs nothing extra.

WHAT IT IS NOT. It is not a prevalence rate for the vibe-coded population as a
whole. The sample is drawn from repositories carrying `lovable-tagger`, so
every number here is conditional on "generated by Lovable", and the corpus in
measure_supabase_rls_yield.py (9 repos, chosen in July for an unrelated CORS
experiment) remains the only unfiltered one. The two are reported separately
and must not be pooled: one is a random-ish slice of vibe-coded repos, the
other is a slice of one generator's output.

NO LIVE CONTACT. Nothing here queries a Supabase project. The hard constraint
from the plan — the measurement must not read rows from a project we do not
own — is satisfied structurally: the only network calls are git fetches of
public repositories.

SAMPLING, STATED BECAUSE IT IS NOT RANDOM. GitHub code search, query
`"lovable-tagger" filename:package.json`, pages 1-2 in the order returned,
fetched 2026-08-18, deduped by repository. GitHub's relevance ordering is not
a uniform sample and there is no way to draw one; what can be said is that
nothing in the ranking is plausibly correlated with whether a repo commits
migrations, which is the only quantity at stake. Search is used for DISCOVERY
only — membership in the corpus is re-decided by reading the repository's own
package.json out of the pinned tree, so a stale or wrong search hit drops out
rather than counting.

Usage:
    python scripts/measure_rls_blind_spot.py
    LIMIT=20 python scripts/measure_rls_blind_spot.py      # a quick pass
    WORKERS=4 python scripts/measure_rls_blind_spot.py
    KEEP=1 python scripts/measure_rls_blind_spot.py        # keep the clones

Writes batch_reports/rls_blind_spot.json — one record per repository, pinned to
the SHA that was read, so the run can be reproduced or disputed.
"""

