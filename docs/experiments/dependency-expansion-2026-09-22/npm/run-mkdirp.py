"""Run the pinned mkdirp 0.5.0 real-project dependency experiment.

Creates an explicit baseline lockfile: upstream has no lockfile, but its original
package.json pins minimist exactly at 0.0.8. npm lifecycle scripts are disabled.
"""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

SOURCE_SHA = "b98bedf92798ed73c87413eaf413d01dbe094a09"
SCANNER_SHA = "0b5c981412ad0a9ab62ad4a7a6da1b90a0acd67b"
BASELINE_LOCK_SHA256 = (
    "dc3f4d520dddd39577c5e3ce54c7d547cf990d36eb516a4893e0b820a1c75013"
)
HERE = Path(__file__).resolve().parent


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def save(path, value):
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scanner-root", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--baseline-lock",
        type=Path,
        help="Reuse archived before-package-lock.json for exact dependency resolution",
    )
    args = parser.parse_args()
    root, source, out = (
        args.scanner_root.resolve(),
        args.source.resolve(),
        args.output.resolve(),
    )
    out.mkdir(parents=True, exist_ok=False)
    sys.path.insert(0, str(root))
    from scripts.verify_dependency_remediation import (
        Case,
        ContractError,
        command,
        execution_env,
        scan,
    )
    from app.scan.remediation_catalog import remediation_record
    from app.scan.cve_match import evaluate_advisory

    assert (
        subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=source, text=True
        ).strip()
        == SOURCE_SHA
    )
    assert not subprocess.check_output(
        ["git", "status", "--porcelain"], cwd=source, text=True
    ).strip()
    subprocess.run(
        ["git", "diff", "--exit-code", SCANNER_SHA, "--", "app", "scripts"],
        cwd=root,
        check=True,
        capture_output=True,
    )
    logs = out / "logs"
    logs.mkdir()
    home = out / "home"
    home.mkdir()
    env = execution_env(home)
    project = out / "project"
    shutil.copytree(
        source, project, ignore=shutil.ignore_patterns(".git", "node_modules")
    )
    catalog_raw = (root / "app/data/cve-catalog.json").read_bytes()
    catalog = json.loads(catalog_raw)
    case = Case("npm", "minimist", "0.0.8", "0.2.4", "mkdirp", "0.5.0", 9)
    common = [
        "--ignore-scripts",
        "--no-audit",
        "--no-fund",
        "--registry=https://registry.npmjs.org",
    ]
    report = {
        "schema_version": 1,
        "experiment_id": "mkdirp-minimist-real-project",
        "status": "unavailable",
        "scanner_commit": SCANNER_SHA,
        "catalog_sha256": digest(catalog_raw),
        "catalog_sources": catalog["sources"],
        "upstream": {
            "repository": "https://github.com/isaacs/node-mkdirp.git",
            "tag": "0.5.0",
            "commit": SOURCE_SHA,
        },
        "original_manifest_sha256": digest((source / "package.json").read_bytes()),
        "baseline_lock": (
            "Generated by npm from the unchanged original exact minimist 0.0.8 pin; "
            "not an upstream lockfile."
        ),
        "node_version": command(
            ["node", "--version"], project, env, logs / "node-version.log"
        ).strip(),
        "npm_version": command(
            ["npm", "--version"], project, env, logs / "npm-version.log"
        ).strip(),
        "regression_source": "https://github.com/minimistjs/minimist/blob/7efb22a518b53b06f5b02a1038a88bd6290c2846/test/proto.js",
        "upstream_tests": ["node test/mkdirp.js", "node test/sync.js"],
        "stages": [],
    }
    save(out / "result.json", report)
    try:
        if args.baseline_lock:
            assert digest(args.baseline_lock.read_bytes()) == BASELINE_LOCK_SHA256, (
                "archived_baseline_hash_mismatch"
            )
            shutil.copyfile(args.baseline_lock.resolve(), project / "package-lock.json")
            report["baseline_lock_source"] = (
                "archived lock supplied with --baseline-lock"
            )
        else:
            command(
                ["npm", "install", "--package-lock-only", *common],
                project,
                env,
                logs / "preparation-resolve.log",
                install=True,
            )
            report["baseline_lock_source"] = (
                "generated from unchanged upstream package.json"
            )
        original = {
            f: (project / f).read_bytes() for f in ("package.json", "package-lock.json")
        }
        assert original["package.json"] == (source / "package.json").read_bytes()
        packages = json.loads(original["package-lock.json"])["packages"]
        assert (
            json.loads(original["package.json"])["dependencies"]["minimist"] == "0.0.8"
        )
        assert packages["node_modules/minimist"]["version"] == "0.0.8"
        assert not any(p.endswith("/camelcase") for p in packages), (
            "blocked_dependency_not_retried"
        )
        for stage in ("before", "after", "restored"):
            for f, raw in original.items():
                (project / f).write_bytes(raw)
            if stage == "after":
                command(
                    ["npm", "pkg", "set", "dependencies.minimist=0.2.4"],
                    project,
                    env,
                    logs / "after-manifest.log",
                )
                command(
                    ["npm", "install", "--package-lock-only", *common],
                    project,
                    env,
                    logs / "after-resolve.log",
                    install=True,
                )
            files = {f: (project / f).read_bytes() for f in original}
            evidence = scan(files, case, catalog)
            findings = [
                f
                for f in evidence["findings"]
                if f["claim_evidence"]["package"] == "minimist"
            ]
            if stage == "before":
                cards = [remediation_record(f["claim_evidence"]) for f in findings]
                assert cards and all("0.2.4" in c["candidate_versions"] for c in cards)
                report["cards"] = cards
            row = {
                "name": stage,
                "manifest_sha256": {f: digest(b) for f, b in files.items()},
                "scan": evidence,
                "target_findings": len(findings),
            }
            for f, raw in files.items():
                (out / (stage + "-" + f)).write_bytes(raw)
            report["stages"].append(row)
            save(out / "result.json", report)
            command(
                ["npm", "ci", *common],
                project,
                env,
                logs / (stage + "-install.log"),
                install=True,
                timeout=180,
            )
            for test in ("mkdirp", "sync"):
                command(
                    ["node", "test/" + test + ".js"],
                    project,
                    env,
                    logs / (stage + "-" + test + "-tests.log"),
                )
            probe = json.loads(
                command(
                    ["node", str(HERE / "mkdirp-probe.cjs")],
                    project,
                    env,
                    logs / (stage + "-probe.log"),
                )
            )
            listing = json.loads(
                command(
                    ["npm", "ls", "minimist", "--all", "--json"],
                    project,
                    env,
                    logs / (stage + "-npm-ls.json"),
                )
            )
            installed = {i["path"]: i["version"] for i in probe["installations"]}
            locked = {
                p: v["version"]
                for p, v in json.loads(files["package-lock.json"])["packages"].items()
                if p.endswith("/minimist")
            }
            assert installed == locked
            assessments = [
                {
                    "path": p,
                    "version": v,
                    "entries": [
                        {"id": a["id"], **evaluate_advisory(v, "npm", a)}
                        for a in catalog["packages"]["npm:minimist"]
                    ],
                }
                for p, v in locked.items()
            ]
            assert all(
                a["status"] in {"affected", "unaffected"} and not a["unresolved_ranges"]
                for i in assessments
                for a in i["entries"]
            )
            root_probe = next(
                i
                for i in probe["installations"]
                if i["path"] == "node_modules/minimist"
            )
            assert root_probe["version"] == ("0.2.4" if stage == "after" else "0.0.8")
            assert root_probe["regression_passed"] == (stage == "after")
            if stage == "after":
                assert not findings
                assert all(
                    a["status"] == "unaffected"
                    for i in assessments
                    for a in i["entries"]
                )
                assert all(i["regression_passed"] for i in probe["installations"])
            else:
                assert findings
            row.update(
                probe=probe,
                locked_assessments=assessments,
                npm_ls=listing,
                upstream_tests_passed=True,
            )
            save(out / (stage + "-evidence.json"), row)
            save(out / "result.json", report)
        before, after, restored = report["stages"]
        assert (
            before["manifest_sha256"] == restored["manifest_sha256"]
            and before["scan"] == restored["scan"]
            and before["probe"] == restored["probe"]
        )
        a = json.loads((out / "before-package-lock.json").read_text())["packages"]
        b = json.loads((out / "after-package-lock.json").read_text())["packages"]
        changes = [
            {
                "path": p,
                "before": a.get(p, {}).get("version"),
                "after": b.get(p, {}).get("version"),
            }
            for p in sorted(a.keys() | b.keys())
            if not p.endswith("/minimist")
            and a.get(p, {}).get("version") != b.get(p, {}).get("version")
        ]
        assert not changes
        report.update(
            status="passed",
            root_dependency_regression_verified=True,
            all_target_installations_unaffected=True,
            restored_exactly=True,
            unrelated_version_changes=changes,
            automatic_patch=False,
            application_exploit_verified=False,
            limitations=[
                "Historical public project; generated baseline lock.",
                "Two original filesystem test files (9 assertions) plus 5 consumer "
                "CLI checks, not the full suite.",
                "Dependency-level prototype pollution regression; "
                "no remote application exploit claim.",
                "Other project vulnerabilities and unknown catalog "
                "assessments remain unresolved.",
            ],
        )
    except AssertionError as exc:
        report.update(status="failed", reason="AssertionError: " + str(exc))
    except ContractError as exc:
        report.update(status=exc.status, reason=exc.reason)
    except Exception as exc:
        report.update(status="unavailable", reason=type(exc).__name__ + ": " + str(exc))
    save(out / "result.json", report)
    print(
        json.dumps(
            {
                "status": report["status"],
                "reason": report.get("reason"),
                "output": str(out),
            }
        )
    )
    return {"passed": 0, "failed": 1, "unavailable": 2}[report["status"]]


if __name__ == "__main__":
    raise SystemExit(main())
